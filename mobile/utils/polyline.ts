/**
 * Decodes a Google Encoded Polyline string into an array of { latitude, longitude } objects.
 * Based on Google's Polyline Algorithm Format.
 */
export function decodePolyline(encoded: string): { latitude: number; longitude: number }[] {
  if (!encoded || typeof encoded !== 'string') {
    return [];
  }

  const points: { latitude: number; longitude: number }[] = [];
  let index = 0;
  const len = encoded.length;
  let lat = 0;
  let lng = 0;

  try {
    while (index < len) {
      let b: number;
      let shift = 0;
      let result = 0;
      do {
        b = encoded.charCodeAt(index++) - 63;
        result |= (b & 0x1f) << shift;
        shift += 5;
      } while (b >= 0x20);
      const dlat = (result & 1) !== 0 ? ~(result >> 1) : result >> 1;
      lat += dlat;

      shift = 0;
      result = 0;
      do {
        b = encoded.charCodeAt(index++) - 63;
        result |= (b & 0x1f) << shift;
        shift += 5;
      } while (b >= 0x20);
      const dlng = (result & 1) !== 0 ? ~(result >> 1) : result >> 1;
      lng += dlng;

      points.push({
        latitude: lat / 1e5,
        longitude: lng / 1e5,
      });
    }
  } catch (e) {
    console.warn('[decodePolyline] Error decoding polyline:', e);
  }

  return points;
}

